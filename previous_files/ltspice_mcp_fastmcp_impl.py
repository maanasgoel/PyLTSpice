def check_ltspice_executable():
    """Checks if the LTspice executable is valid."""
    # On non-Windows, we check for the Wine wrapper and the underlying file path.
    if sys.platform != "win32":
        if not shutil.which(WINE_COMMAND):
            return False, f"'{WINE_COMMAND}' command not found. Wine is required to run LTspice on macOS/Linux."
    
    # The path inside Wine needs to be checked from the host perspective
    if not os.path.exists(os.path.expanduser(LTSPICE_EXECUTABLE_PATH)):
         return False, f"LTspice executable not found at '{LTSPICE_EXECUTABLE_PATH}'. Please check the LTSPICE_EXECUTABLE_PATH variable."
    return True, ""


@mcp.tool()
async def create_simulation_session(netlist_text: str) -> dict:
    """
    DEPRECATED: Use the more specific `create_rc_transient_netlist` for standard RC circuits.
    This tool remains for custom/complex netlists.

    Creates a netlist file and a new simulation session directory.
    This is the first step for any new simulation.
    The AI should first generate the complete SPICE netlist content as a string based on the user's request.
    Then, it should call this tool with the generated netlist string as the 'netlist_text' argument.
    This tool will handle creating the necessary files and directories.
    Do not try to write files directly using generic file tools.

    Example Netlist for a transient analysis of an RC circuit:
    '''
    * Simple RC Circuit
    V1 Vin 0 PULSE(0 5 0 1n)
    R1 Vin Vout 1k
    C1 Vout 0 1uF
    .tran 5m
    .end
    '''
    """
    try:
        # Create a unique, timestamped directory for the session
        timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
        session_dir = os.path.join(BASE_OUTPUT_DIR, timestamp)
        os.makedirs(session_dir, exist_ok=True)

        netlist_path = os.path.join(session_dir, "circuit.net")
        with open(netlist_path, "w") as f:
            f.write(netlist_text)

        logging.info(f"Created simulation session in: {session_dir}")
        return {
            "status": "success",
            "session_dir": session_dir,
            "netlist_path": netlist_path,
            "message": f"Session created at {session_dir}. Netlist saved to {netlist_path}.",
        }
    except Exception as e:
        logging.error(f"Failed to create simulation session: {e}", exc_info=True)
        return {"status": "error", "message": str(e)}


@mcp.tool()
async def create_rc_transient_netlist(
    resistance: str, capacitance: str, pulse_v_on: str, pulse_width: str, sim_duration: str
) -> dict:
    """
    Creates a complete and correct SPICE netlist for a simple RC circuit transient analysis.
    This tool generates the netlist, creates a session directory, and saves the file.
    Use this for standard RC circuit simulations.

    Args:
        resistance (str): Resistance value (e.g., "1k").
        capacitance (str): Capacitance value (e.g., "1uF").
        pulse_v_on (str): The "on" voltage for the pulse source (e.g., "5V").
        pulse_width (str): The duration of the pulse (e.g., "2.5m").
        sim_duration (str): The total transient simulation time (e.g., "5m").
    """
    # Generate a syntactically correct PULSE function.
    # PULSE(Vinitial Von Tdelay Trise Tfall Ton Tperiod)
    # We'll use small rise/fall times and no delay.
    pulse_params = f"PULSE(0 {pulse_v_on} 0 1n 1n {pulse_width} {sim_duration})"

    netlist_content = f"""* Simple RC Circuit - Generated by MCP
V1 Vin 0 {pulse_params}
R1 Vin Vout {resistance}
C1 Vout 0 {capacitance}
.tran {sim_duration}
.end
"""
    # We can await it because we made it async
    return await create_simulation_session(netlist_content)


@mcp.tool()
async def open_in_ltspice(netlist_path: str) -> dict:
    """
    Opens the specified .net file in the LTspice GUI for visual inspection.
    """
    is_valid, message = check_ltspice_executable()
    if not is_valid:
        logging.error(message)
        return {"status": "error", "message": message}

    if not os.path.exists(netlist_path):
        message = f"Netlist file not found at '{netlist_path}'"
        logging.error(message)
        return {"status": "error", "message": message}

    try:
        cmd = [WINE_COMMAND, LTSPICE_EXECUTABLE_PATH, os.path.abspath(netlist_path)]
        logging.info(f"Opening LTspice with command: {' '.join(cmd)}")
        subprocess.Popen(cmd)
        message = f"Successfully launched LTspice with {os.path.basename(netlist_path)}."
        return {"status": "success", "message": message}
    except Exception as e:
        logging.error(f"Failed to open LTspice: {e}", exc_info=True)
        return {"status": "error", "message": str(e)}


@mcp.tool()
async def run_simulation(netlist_path: str, session_dir: str) -> dict:
    """
    Runs the simulation for the given netlist in batch mode.
    Outputs (.raw, .log) will be saved in the specified session directory.
    """
    is_valid, message = check_ltspice_executable()
    if not is_valid:
        logging.error(message)
        return {"status": "error", "message": message}

    if not os.path.exists(netlist_path):
        message = f"Netlist file not found at '{netlist_path}'"
        logging.error(message)
        return {"status": "error", "message": message}

    try:
        # To make Wine path handling robust, we run the command from within the session directory
        # and refer to the netlist file by its simple name.
        netlist_filename = os.path.basename(netlist_path)
        cmd = [WINE_COMMAND, LTSPICE_EXECUTABLE_PATH, "-b", netlist_filename]
        
        logging.info(f"Running simulation with command: {' '.join(cmd)}")
        logging.info(f"Working directory: {session_dir}")

        process = subprocess.run(
            cmd,
            cwd=session_dir,  # Run from the session directory
            capture_output=True,
            text=True,
            check=False # Don't throw exception for non-zero exit codes
        )

        log_file_path = os.path.join(session_dir, "circuit.log")
        raw_file_path = os.path.join(session_dir, "circuit.raw")

        if process.returncode != 0 or not os.path.exists(raw_file_path):
            log_content = ""
            if os.path.exists(log_file_path):
                with open(log_file_path, 'r') as f:
                    log_content = f.read()
            
            message = f"Simulation failed. Return code: {process.returncode}. Log content: {log_content}"
            logging.error(message)
            logging.error(f"STDOUT: {process.stdout}")
            logging.error(f"STDERR: {process.stderr}")
            return {"status": "error", "message": message}

        message = f"Simulation successful. Raw data saved to {raw_file_path}."
        logging.info(message)
        return {
            "status": "success",
            "raw_file_path": raw_file_path,
            "log_file_path": log_file_path,
            "message": message,
        }

    except Exception as e:
        logging.error(f"An exception occurred during simulation: {e}", exc_info=True)
        return {"status": "error", "message": str(e)}


@mcp.tool()
async def list_available_traces(raw_file_path: str) -> dict:
    """
    Lists all available signals (traces) from a given .raw simulation output file.
    """
    if not os.path.exists(raw_file_path):
        message = f"RAW file not found at '{raw_file_path}'"
        logging.error(message)
        return {"status": "error", "message": message}
    try:
        raw_reader = LTSpiceRawRead(raw_file_path)
        traces = raw_reader.get_trace_names()
        logging.info(f"Available traces: {traces}")
        return {"status": "success", "traces": traces}
    except Exception as e:
        logging.error(f"Failed to read traces from RAW file: {e}", exc_info=True)
        return {"status": "error", "message": str(e)}


@mcp.tool()
async def plot_specific_traces(raw_file_path: str, session_dir: str, trace_names: list[str]) -> dict:
    """
    Generates and displays a plot for a list of specified traces from a .raw file.
    The plot is also saved as a PNG file in the session directory.
    """
    if not os.path.exists(raw_file_path):
        message = f"RAW file not found at '{raw_file_path}'"
        logging.error(message)
        return {"status": "error", "message": message}

    try:
        raw_reader = LTSpiceRawRead(raw_file_path)
        
        plt.figure(figsize=(10, 6))
        plt.title("LTspice Simulation Plot")
        plt.xlabel("Time (s)")
        plt.ylabel("Value")
        plt.grid(True)

        time_trace = raw_reader.get_trace('time')
        x = time_trace.get_wave()

        for trace_name in trace_names:
            trace = raw_reader.get_trace(trace_name)
            if not trace:
                message = f"Trace '{trace_name}' not found in the raw file."
                logging.warning(message)
                continue
            y = trace.get_wave()
            # Filter out negative time values which can occur and mess up plots
            if len(x) != len(y):
                logging.warning(f"Skipping trace '{trace_name}' due to mismatched data lengths.")
                continue
            x_filtered, y_filtered = zip(*[(t, v) for t, v in zip(x, y) if t >= 0])
            plt.plot(x_filtered, y_filtered, label=trace_name)
        
        plt.legend()
        
        # Generate a safe filename from the trace names
        plot_filename = f"plot_{'_'.join(trace_names)}.png".replace('(', '').replace(')', '').replace(',', '_')
        plot_path = os.path.join(session_dir, plot_filename)
        
        plt.savefig(plot_path)
        plt.close() # Close the figure to free memory
        
        logging.info(f"Plot saved to {plot_path}")
        return {
            "status": "success",
            "plot_path": plot_path,
            "message": f"Plot of {', '.join(trace_names)} created successfully and saved to {plot_path}"
        }

    except Exception as e:
        logging.error(f"Failed to plot traces: {e}", exc_info=True)
        return {"status": "error", "message": str(e)}


